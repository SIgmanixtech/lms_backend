// Writes every role route file under src/app/api/v1/<admin|tutor|student>/ from the lists in
// src/shared/lib/api/contracts.ts (ROLE_API, ROLE_TABLES, ROLE_FUNCTIONS, ROLE_UPLOAD_BUCKETS).
//   npm run generate-routes            rewrite the role folders
//   npm run generate-routes -- --check exit 1 if the files on disk differ
// Each file only binds shared handlers to its role (src/api/data-routes.ts `serve`), so behaviour is defined once.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { APP_ROLES, DATA_TABLES, ROLE_API, ROLE_FUNCTIONS, ROLE_SEGMENT, ROLE_UPLOAD_BUCKETS, tableMethods, tableSegment } from "../src/shared/lib/api/contracts.ts";

type Entry = { op: string } | { table: string; scope: "collection" | "item" } | { fn: string } | { files: "upload" | "sign" };

const here = path.dirname(fileURLToPath(import.meta.url));
const V1 = path.join(here, "..", "src", "app", "api", "v1");
const check = process.argv.includes("--check");

/** `classes/:class_id/attendance/:student_id` -> `classes/[id]/attendance/[subId]` (Next needs one param name per level). */
const folderOf = (template: string) => {
  let n = 0;
  return template.split("/").map((s) => (s.startsWith(":") ? (n++ === 0 ? "[id]" : "[subId]") : s)).join("/");
};

const files = new Map<string, { role: string; entries: Entry[]; methods: string[] }>();
const add = (role: string, folder: string, entry: Entry, methods: string[]) => {
  const key = `${ROLE_SEGMENT[role as keyof typeof ROLE_SEGMENT]}/${folder}`;
  const f = files.get(key) ?? { role, entries: [], methods: [] };
  f.entries.push(entry);
  for (const m of methods) {
    if (f.methods.includes(m)) throw new Error(`${key}: ${m} claimed twice`);
    f.methods.push(m);
  }
  files.set(key, f);
};

for (const role of APP_ROLES) {
  for (const [op, def] of Object.entries(ROLE_API)) {
    if ((def.roles as readonly string[]).includes(role)) add(role, folderOf(def.path), { op }, [def.method]);
  }
  for (const table of DATA_TABLES) {
    const { collection, item } = tableMethods(role, table);
    const withHead = (ms: string[]) => (ms.includes("GET") ? [...ms, "HEAD"] : ms);
    if (collection.length) add(role, tableSegment(table), { table, scope: "collection" }, withHead(collection));
    if (item.length) add(role, `${tableSegment(table)}/[id]`, { table, scope: "item" }, withHead(item));
  }
  for (const [fn, def] of Object.entries(ROLE_FUNCTIONS)) {
    if ((def.roles as readonly string[]).includes(role)) add(role, def.path, { fn }, ["POST"]);
  }
  if (ROLE_UPLOAD_BUCKETS[role].length) add(role, "files/[...path]", { files: "upload" }, ["POST"]);
  add(role, "files/sign/[...path]", { files: "sign" }, ["POST"]);
}

const ORDER = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE"];
const render = (key: string, f: { role: string; entries: Entry[]; methods: string[] }) => {
  const methods = [...f.methods].sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b));
  return `import { serve } from "@backend/api/data-routes";

// Generated by scripts/generate-role-routes.ts from contracts.ts: change the lists there and regenerate.
/** ${methods.join(", ")} /api/v1/${key.replace(/\[\.\.\.path\]/, "<bucket>/<path>").replace(/\[(id|subId)\]/g, ":$1")} (${f.role} only). */
const routes = serve("${f.role}", ${JSON.stringify(f.entries)});

${methods.map((m) => `export const ${m} = routes.${m}!;`).join("\n")}
export const OPTIONS = routes.OPTIONS;
`;
};

const wanted = new Map([...files].map(([key, f]) => [path.join(V1, ...key.split("/"), "route.ts"), render(key, f)]));
const walk = (d: string): string[] => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])) : []);
const existing = Object.values(ROLE_SEGMENT).flatMap((seg) => walk(path.join(V1, seg)));

let diff = 0;
for (const f of existing) if (!wanted.has(f)) { diff++; if (check) console.log(`extra    ${path.relative(V1, f)}`); }
for (const [f, text] of wanted) if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== text) { diff++; if (check) console.log(`differs  ${path.relative(V1, f)}`); }

if (check) {
  console.log(`${wanted.size} role route files, ${diff} out of date.`);
  process.exit(diff ? 1 : 0);
}
for (const seg of Object.values(ROLE_SEGMENT)) fs.rmSync(path.join(V1, seg), { recursive: true, force: true });
for (const [f, text] of wanted) { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); }
console.log(`${wanted.size} role route files written.`);
